export type I18nMessages = (typeof MESSAGES)[AppLocale];

function detectDefaultLocale(): AppLocale {
  if (typeof navigator === 'undefined') return 'zh';
  const lang = (navigator.language || '').toLowerCase();
  if (lang.startsWith('zh')) return 'zh';
  if (lang.startsWith('ja')) return 'ja';
  return 'en';
}

function resolveInitialLocale(): AppLocale {
  const saved = loadPersistedState().locale;
  if (saved === 'zh' || saved === 'en' || saved === 'ja') {
    return saved;
  }
  return detectDefaultLocale();
}

export const currentLocale = ref<AppLocale>(resolveInitialLocale());

function applyDocumentLang(locale: AppLocale) {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = locale === 'zh' ? 'zh-CN' : locale === 'ja' ? 'ja' : 'en';
}

applyDocumentLang(currentLocale.value);

export function setLocale(locale: AppLocale): void {
  if (currentLocale.value === locale) return;
  currentLocale.value = locale;
  applyDocumentLang(locale);
  patchPersistedState({ locale });
}

export function getPenpaLangCode(locale: AppLocale): 'ZH' | 'EN' | 'JP' {
  if (locale === 'zh') return 'ZH';
  if (locale === 'ja') return 'JP';
  return 'EN';
}

export function formatMessage(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k: string) =>
    k in params ? String(params[k]) : `{${k}}`,
  );
}

export const messages = computed<I18nMessages>(() => MESSAGES[currentLocale.value]);
